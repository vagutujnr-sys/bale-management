function isAppLanguage(value: string | null): value is AppLanguage {
  return value === "en" || value === "sn" || value === "nd";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const savedLanguage = window.localStorage.getItem("bale-contract-language");
    if (isAppLanguage(savedLanguage)) setLanguage(savedLanguage);
    setReady(true);
  }, []);

  useEffect(() => {
    if (!ready) return;
    window.localStorage.setItem("bale-contract-language", language);
    document.documentElement.lang = language;
  }, [language, ready]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (text, values) => {
        const translated = language === "en" ? text : (translations[language][text] ?? text);
        return values
          ? translated.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""))
          : translated;
      },
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
